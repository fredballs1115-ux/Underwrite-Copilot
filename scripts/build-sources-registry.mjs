// Compile docs/data-sources/json/<metro>.sources.json into the single
// machine-readable docs/data-sources/sources.json, validating every entry
// against the registry protocol. Fails LOUDLY on malformed entries so a bad
// research file can't silently poison the union.
//
//   node scripts/build-sources-registry.mjs
//
// The union is generated — never hand-edit it (RESEARCH_PROTOCOL.md).

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonDir = join(root, "docs", "data-sources", "json");
const outPath = join(root, "docs", "data-sources", "sources.json");

const CATEGORIES = new Set([
  "parcel_assessment",
  "recorder_deeds",
  "zoning",
  "broker_comps",
  "tax_rates",
  "permits_co",
  "violations_liens",
  "sheriff_foreclosure",
  "evictions_rent_reg",
  "incentive_zones",
  "environmental",
  "gis_open_data",
  "rent_demand",
]);
const ACCESS = new Set(["api", "bulk_download", "gis_service", "scrape", "manual"]);
const DIFFICULTY = new Set(["easy", "medium", "hard"]);
const VERIFICATION = new Set(["search-confirmed", "unverified"]);
const REQUIRED = [
  "metro",
  "jurisdiction",
  "category",
  "source_name",
  "verification",
  "access_method",
  "difficulty",
];

const files = readdirSync(jsonDir).filter((f) => f.endsWith(".sources.json")).sort();
const problems = [];
const entries = [];

for (const f of files) {
  const metroId = f.replace(/\.sources\.json$/, "");
  let arr;
  try {
    arr = JSON.parse(readFileSync(join(jsonDir, f), "utf8"));
  } catch (err) {
    problems.push(`${f}: unparseable JSON — ${err.message}`);
    continue;
  }
  if (!Array.isArray(arr)) {
    problems.push(`${f}: top level must be an array`);
    continue;
  }
  arr.forEach((e, i) => {
    const where = `${f}[${i}]`;
    for (const k of REQUIRED) {
      if (!e[k] || typeof e[k] !== "string") problems.push(`${where}: missing/non-string ${k}`);
    }
    if (e.metro && e.metro !== metroId)
      problems.push(`${where}: metro "${e.metro}" ≠ filename metro "${metroId}"`);
    if (e.category && !CATEGORIES.has(e.category))
      problems.push(`${where}: unknown category "${e.category}"`);
    if (e.access_method && !ACCESS.has(e.access_method))
      problems.push(`${where}: unknown access_method "${e.access_method}"`);
    if (e.difficulty && !DIFFICULTY.has(e.difficulty))
      problems.push(`${where}: unknown difficulty "${e.difficulty}"`);
    if (e.verification && !VERIFICATION.has(e.verification))
      problems.push(`${where}: unknown verification "${e.verification}"`);
    // URL discipline: a search-confirmed entry must carry a real-looking URL;
    // an unverified one must say what was tried.
    if (e.verification === "search-confirmed" && !/^https?:\/\//.test(e.url ?? ""))
      problems.push(`${where}: search-confirmed but url is "${e.url ?? ""}"`);
    if (e.verification === "unverified" && !e.verification_note)
      problems.push(`${where}: unverified without verification_note`);
    entries.push(e);
  });
}

if (problems.length) {
  console.error(`sources registry FAILED validation (${problems.length} problems):`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

entries.sort(
  (a, b) =>
    a.metro.localeCompare(b.metro) ||
    a.jurisdiction.localeCompare(b.jurisdiction) ||
    a.category.localeCompare(b.category) ||
    a.source_name.localeCompare(b.source_name)
);

const counts = {};
for (const e of entries) counts[e.metro] = (counts[e.metro] ?? 0) + 1;

writeFileSync(
  outPath,
  JSON.stringify(
    {
      $schema_note:
        "Generated by scripts/build-sources-registry.mjs from docs/data-sources/json/*.sources.json — do not hand-edit. Entry fields per docs/data-sources/RESEARCH_PROTOCOL.md.",
      generated_at: new Date().toISOString().slice(0, 10),
      entry_count: entries.length,
      metros: counts,
      sources: entries,
    },
    null,
    2
  ) + "\n"
);
console.log(
  `sources.json written: ${entries.length} entries across ${Object.keys(counts).length} metros (${files.length} files).`
);
